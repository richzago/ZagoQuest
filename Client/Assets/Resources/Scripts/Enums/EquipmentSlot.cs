/// <summary>
/// Slots de equipamento disponíveis para o jogador.
/// Corresponde ao enum do servidor.
/// </summary>
public enum EquipmentSlot
{
    HELMET,   // Capacete/elmo
    ARMOR,    // Armadura/peitoral
    LEGS,     // Calças/pernas
    BOOTS,    // Botas
    WEAPON,   // Arma principal
    SHIELD,   // Escudo (ou segunda mão)
    RING,     // Anel
    AMULET,   // Amuleto/colar
    BACKPACK, // Mochila
    USEFUL    // Iscas, ferramentas, acessórios especiais
}